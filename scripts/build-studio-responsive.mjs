import {readFile,writeFile} from 'node:fs/promises';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';
// Keep page breakpoints isolated from Studio's surrounding window and generate
// the editor counterpart with identical specificity and template exclusions.
const file=new URL('../app/globals.css',import.meta.url);
const root=postcss.parse(await readFile(file,'utf8'));
const mirror=postcss.root();
const exclusion=':not(:where(.studio-artboard, .studio-artboard *))';
root.walkAtRules('media',at=>{
 if(!/\(\s*(?:max|min)-width\s*:/.test(at.params))return;
 const copy=at.clone(); copy.name='container';copy.params='studioPage '+at.params;
 copy.walkRules(rule=>{
  if(rule.selector.includes(':not([data-editor-viewport])')){rule.remove();return;}
  rule.selector=selectorParser().processSync(rule.selector.replaceAll(exclusion,''));
  rule.selectors=rule.selectors.map(s=>':where(.studio-artboard) '+s);
 });
 copy.walkDecls(d=>{d.value=d.value.replace(/(-?(?:\d*\.)?\d+)vw\b/gi,'$1cqw')});
 if(copy.nodes.length)mirror.append(copy);
 at.walkRules(rule=>{
  if(rule.selector.includes(':not([data-editor-viewport])'))return;
  rule.selector=selectorParser(selectors=>selectors.each(selector=>{
   if(selector.toString().includes(exclusion))return;
   const node=selectorParser().astSync(exclusion).first.first.clone();
   const pseudo=selector.nodes.find(n=>n.type==='pseudo'&&n.value.startsWith('::'));
   if(pseudo)selector.insertBefore(pseudo,node);else selector.append(node);
  })).processSync(rule.selector);
 });
});
await writeFile(file,root.toString());
await writeFile(new URL('../app/studio-responsive.css',import.meta.url),'/* Generated by scripts/build-studio-responsive.mjs from globals.css. */\n'+mirror.toString()+'\n');
