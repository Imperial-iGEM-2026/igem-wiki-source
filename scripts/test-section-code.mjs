import assert from 'node:assert/strict';
import { Readable } from 'node:stream';
import { createSectionCodeUploads, sectionCodeBytes, checkSectionCode, codeHash } from '../server/mcp-section-code.mjs';

const fail = (status, message) => Object.assign(new Error(message), { status });
let now = 1000;
const uploads = createSectionCodeUploads({ fail, now: () => now });
const link = { token_hash: 'test-link', expires_at: now + 3600000 };
const args = content => ({ page: 'home', id: 'component', field: 'javascript', ifVersion: 2,
  ifHash: codeHash('old'), size: Buffer.byteLength(content), sha256: codeHash(content), reviewedForUpload: true });
const request = chunks => Object.assign(Readable.from(chunks), { headers: {} });
assert.equal(checkSectionCode('é'.repeat(65536), fail), sectionCodeBytes);
assert.throws(() => checkSectionCode('é'.repeat(65536) + 'x', fail), /131072/);
assert.throws(() => uploads.issue(link, { ...args('abc'), reviewedForUpload: false }), /production artifact/);
assert.throws(() => uploads.issue(link, { ...args('abc'), size: sectionCodeBytes + 1 }), /128 KiB/);
const issued = uploads.issue(link, args('abc'));
const ticket = uploads.get(issued.secret);
let commits = 0;
const commit = (metadata, content) => { commits++; assert.equal(content, 'abc'); return { ok: true, bytes: 3 }; };
await assert.rejects(uploads.receive(request([Buffer.from('abcd')]), ticket, commit), /exceeds/);
await assert.rejects(uploads.receive(request([Buffer.from('ab')]), ticket, commit), /mismatch/);
assert.equal(commits, 0);
assert.equal((await uploads.receive(request([Buffer.from('a'), Buffer.from('bc')]), ticket, commit)).bytes, 3);
assert.equal((await uploads.receive(request([Buffer.from('abc')]), ticket, commit)).alreadyApplied, true);
assert.equal(commits, 1, 'Retry cannot apply a second mutation');
const shortLink = { ...link, expires_at: now + 500 };
const short = uploads.issue(shortLink, args('abc'));
assert.equal(short.expiresAt, shortLink.expires_at);
const shortTicket = uploads.get(short.secret);
now += 501;
assert.equal(uploads.get(short.secret), undefined);
await assert.rejects(uploads.receive(request([Buffer.from('abc')]), shortTicket, commit), /expired/);
const slow = uploads.issue(link, args('abc'));
const slowTicket = uploads.get(slow.secret);
const slowBody = request((async function* () { yield Buffer.from('ab'); now += 600001; yield Buffer.from('c'); })());
await assert.rejects(uploads.receive(slowBody, slowTicket, commit), /expired/);
assert.equal(commits, 1);
assert.equal(uploads.get(slow.secret), undefined);
const invalid = Buffer.from([0xc0, 0xaf]);
const invalidTicket = uploads.get(uploads.issue(link, args(invalid)).secret);
await assert.rejects(uploads.receive(request([invalid]), invalidTicket, commit), /UTF-8/);
console.log('PASS: code uploads enforce exact UTF-8 bytes, bounded streaming, expiry, agent review and idempotent retries.');
